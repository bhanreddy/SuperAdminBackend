CREATE OR REPLACE FUNCTION ingest_website_enquiry(
  p_name TEXT,
  p_email TEXT,
  p_phone TEXT,
  p_message TEXT,
  p_product TEXT,
  p_website_source TEXT,
  p_channel_code TEXT,
  p_campaign TEXT,
  p_organization TEXT,
  p_budget_range TEXT
) RETURNS TABLE (id UUID, created_at TIMESTAMPTZ)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  channel UUID;
  raw_product TEXT;
  vertical TEXT;
BEGIN
  IF char_length(trim(COALESCE(p_name, ''))) < 2 THEN
    RAISE EXCEPTION 'Name is required';
  END IF;
  IF NULLIF(trim(COALESCE(p_email, '')), '') IS NULL AND NULLIF(trim(COALESCE(p_phone, '')), '') IS NULL THEN
    RAISE EXCEPTION 'Email or phone is required';
  END IF;
  raw_product := COALESCE(NULLIF(trim(p_product), ''), 'SchoolIMS');
  vertical := CASE
    WHEN upper(raw_product) IN ('SCHOOL', 'SCHOOLIMS') THEN 'SCHOOL'
    WHEN upper(raw_product) IN ('MEDICAL', 'RETAIL', 'OTHER') THEN upper(raw_product)
    ELSE left(raw_product, 40)
  END;
  SELECT c.id INTO channel FROM crm_acquisition_channels c
  WHERE c.code = COALESCE(NULLIF(trim(p_channel_code), ''), 'WEBSITE') AND c.archived_at IS NULL;
  RETURN QUERY
  INSERT INTO enquiries (
    name, email, phone, organization, message, budget_range, website_source, category, status,
    pipeline_stage_code, outcome, acquisition_channel_id, campaign_name,
    product_vertical, intake_queue, sales_model_version
  ) VALUES (
    trim(p_name),
    NULLIF(lower(trim(COALESCE(p_email, ''))), ''),
    NULLIF(trim(COALESCE(p_phone, '')), ''),
    NULLIF(trim(COALESCE(p_organization, '')), ''),
    NULLIF(trim(COALESCE(p_message, '')), ''),
    NULLIF(trim(COALESCE(p_budget_range, '')), ''),
    COALESCE(NULLIF(trim(p_website_source), ''), 'NEXSYRUS_WEBSITE'),
    raw_product,
    'NEW',
    'NEW',
    'OPEN',
    channel,
    NULLIF(trim(COALESCE(p_campaign, '')), ''),
    vertical,
    'UNASSIGNED_INTAKE',
    1
  )
  RETURNING enquiries.id, enquiries.created_at;
END $$;

