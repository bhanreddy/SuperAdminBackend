CREATE OR REPLACE FUNCTION crm_school_sales_class(p enquiries)
RETURNS TEXT
LANGUAGE sql STABLE AS $$
  WITH acc AS (
    SELECT upper(btrim(vertical)) AS vertical
    FROM crm_accounts WHERE id = p.account_id
  ),
  tok AS (
    SELECT
      upper(btrim(COALESCE(p.product_vertical, ''))) AS product,
      upper(btrim(COALESCE(p.category, ''))) AS category
  )
  SELECT CASE
    WHEN p.account_id IS NOT NULL AND EXISTS (
      SELECT 1 FROM acc, tok
      WHERE acc.vertical = 'SCHOOL'
        AND (tok.product IN ('MEDICAL', 'RETAIL', 'OTHER') OR tok.category IN ('MEDICAL', 'RETAIL', 'OTHER'))
    ) THEN 'CONFLICT'
    WHEN p.account_id IS NOT NULL AND EXISTS (
      SELECT 1 FROM acc, tok
      WHERE acc.vertical <> 'SCHOOL'
        AND (tok.product IN ('SCHOOL', 'SCHOOLIMS') OR tok.category IN ('SCHOOL', 'SCHOOLIMS'))
    ) THEN 'CONFLICT'
    WHEN p.account_id IS NOT NULL AND EXISTS (SELECT 1 FROM acc WHERE vertical = 'SCHOOL') THEN 'SCHOOL'
    WHEN p.account_id IS NULL AND EXISTS (
      SELECT 1 FROM tok
      WHERE product IN ('SCHOOL', 'SCHOOLIMS') OR category IN ('SCHOOL', 'SCHOOLIMS')
    ) THEN 'SCHOOL'
    ELSE 'OTHER'
  END;
$$;

