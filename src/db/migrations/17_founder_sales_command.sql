CREATE CONSTRAINT TRIGGER enquiries_next_action_guard
AFTER INSERT OR UPDATE OF next_action_task_id ON enquiries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION crm_enforce_next_action();

