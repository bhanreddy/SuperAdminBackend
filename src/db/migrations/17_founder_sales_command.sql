CREATE OR REPLACE FUNCTION crm_enforce_next_action() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  task_enquiry UUID;
  task_status TEXT;
BEGIN
  IF NEW.next_action_task_id IS NULL THEN
    RETURN NULL;
  END IF;
  SELECT enquiry_id, status INTO task_enquiry, task_status
  FROM crm_tasks WHERE id = NEW.next_action_task_id;
  IF task_enquiry IS DISTINCT FROM NEW.id OR task_status NOT IN ('OPEN', 'IN_PROGRESS') THEN
    RAISE EXCEPTION 'designated next action must be an open task on this enquiry';
  END IF;
  RETURN NULL;
END $$;

