CREATE OR REPLACE FUNCTION crm_touch_designated_follow_up() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE'
     AND OLD.due_at IS NOT DISTINCT FROM NEW.due_at
     AND OLD.status IS NOT DISTINCT FROM NEW.status THEN
    RETURN NULL;
  END IF;
  UPDATE enquiries
  SET updated_at = now()
  WHERE next_action_task_id = NEW.id;
  RETURN NULL;
END $$;

